const assert = require('node:assert/strict');
const classify = require('../backend/xano/checkout-incident-policy.js');
const now = 1000000;
const i = {id:5,order_id:100,provider_slug:'nuitee',environment:'sandbox',status:'booked',updated_at:1,selling_price:241.43,currency:'EUR',checkout_context:{voucher_id:44,confirmation_mail:{status:'sent'},request:{checkin:'2026-11-10'}}};
const o = {payment_status:'paid',provider_sync_status:'confirmed',external_booking_id:'abc'};
const b = [{provider_slug:'nuitee',environment:'sandbox',booking_status:'confirmed',external_booking_id:'abc'}];
const v = [{id:44,status:'active',redemption_status:'active'}];
assert.equal(classify(i,o,b,v,now),null);
assert.ok(classify({...i,status:'processing'},o,[],[],now).reasons.includes('PAID_WITHOUT_BOOKING'));
assert.equal(classify({...i,status:'processing',updated_at:now},o,[],[],now),null);
assert.ok(classify({...i,status:'manual_attention',updated_at:now},o,[],[],now).reasons.includes('MANUAL_REVIEW'));
assert.equal(classify({...i,status:'pending_payment'},{payment_status:'pending'},[],[],now),null);
assert.ok(classify(i,o,[{...b[0],environment:'production'}],v,now).reasons.includes('BOOKING_REFERENCE_MISMATCH'));
assert.ok(classify(i,{...o,status:'refunded'},b,v,now).reasons.includes('REFUNDED_BOOKING_CONFIRMED'));
assert.ok(classify(i,o,[{...b[0],booking_status:'cancelled'}],v,now).reasons.includes('CANCELLED_VOUCHER_ACTIVE'));
assert.ok(classify(i,o,b,[],now).reasons.includes('VOUCHER_MISSING'));
const dirty = {...i,status:'manual_attention',holder:{email:'private@example.test'},stripe_checkout_session_id:'secret-session',stripe_payment_intent_id:'secret-payment'};
const result=JSON.stringify(classify(dirty,o,[],[],now));
assert.ok(!/private@example|secret-session|secret-payment/.test(result));
assert.ok(classify(i,null,[],[],now).reasons.includes('ORDER_MISSING'));
assert.equal(classify(i,o,[...b,{...b[0],external_booking_id:'old',booking_status:'booking_failed_after_payment'}],v,now),null);
console.log('Checkout incident policy: 12 checks passed');
const fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../backend/xano/supplier-checkout-incidents.xs'),'utf8');
const blocks=[...source.matchAll(/code = """([\s\S]*?)"""/g)];
const batch=new Function('$var',blocks[0][1]);
const rows=Array.from({length:51},(_,k)=>({id:k+1}));
assert.deepEqual(batch({records:rows}),{rows:rows.slice(0,50),has_more:true,next_cursor:50});
assert.equal(batch({records:[]}).has_more,false);
const actualPolicy=new Function('$var',blocks[1][1]);
assert.equal(actualPolicy({intent:i,related_order:o,bookings:b,vouchers:v}),null);
console.log('Actual Xano lambdas: pagination boundary and healthy booking passed');
